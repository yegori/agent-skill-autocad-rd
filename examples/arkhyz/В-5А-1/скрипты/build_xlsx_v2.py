def link(cell, sheet):
    cell.value = f"Лист {sheet}" if sheet != "КЖИ" else "КЖИ ЗД-1"
    cell.hyperlink = quote(PDF[sheet])
    cell.font = Font(name=F, color="0563C1", underline="single", size=10)

def header(ws, row, names, widths):
    for i, (n, w) in enumerate(zip(names, widths), 1):
        c = ws.cell(row=row, column=i, value=n)
        c.font = Font(name=F, bold=True, size=10)
        c.fill = HDR
        c.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
        c.border = BRD
        ws.column_dimensions[get_column_letter(i)].width = w

def style_row(ws, row, ncol, fill=None, bold=False):
    for i in range(1, ncol + 1):
        c = ws.cell(row=row, column=i)
        if c.hyperlink is None:
            c.font = Font(name=F, size=10, bold=bold)
        c.border = BRD
        c.alignment = Alignment(vertical="center", wrap_text=True,
                                horizontal=c.alignment.horizontal)
        if fill:
            c.fill = fill


def text(s, x, y, center=False, h=H):
    tb.append(f'(entmake (list (cons 0 "TEXT") (cons 67 1) (cons 410 "ОД") (cons 8 {ls(LAYER)})'
              f' (cons 7 {ls(STYLE)}) (cons 40 {h}) (cons 51 {OBL:.6f}) (cons 1 {ls(s)})'
              f' (list 10 {x:.4f} {y:.4f} 0.0) (list 11 {x:.4f} {y:.4f} 0.0)'
              f' (cons 72 {1 if center else 0}) (cons 73 2)))')


